const SUPPORTED_LANGS = Object.keys(I18N);

function applyLanguage(lang) {
  if (!I18N[lang]) lang = 'es';
  const dict = I18N[lang];

  document.documentElement.setAttribute('lang', lang);
  if (dict['meta.title']) document.title = dict['meta.title'];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict['meta.description']) metaDesc.setAttribute('content', dict['meta.description']);
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle && dict['meta.title']) ogTitle.setAttribute('content', dict['meta.title']);
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc && dict['meta.description']) ogDesc.setAttribute('content', dict['meta.description']);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  const langCurrent = document.getElementById('langCurrent');
  if (langCurrent) langCurrent.textContent = lang.toUpperCase();
  document.querySelectorAll('.lang-menu li').forEach(li => {
    li.classList.toggle('active', li.getAttribute('data-lang') === lang);
  });

  try { localStorage.setItem('elcomal-lang', lang); } catch (e) {}
}

function detectInitialLanguage() {
  try {
    const stored = localStorage.getItem('elcomal-lang');
    if (stored && I18N[stored]) return stored;
  } catch (e) {}
  const params = new URLSearchParams(window.location.search);
  const fromQuery = params.get('lang');
  if (fromQuery && I18N[fromQuery]) return fromQuery;
  const browserLang = (navigator.language || 'es').slice(0, 2);
  if (I18N[browserLang]) return browserLang;
  return 'es';
}
